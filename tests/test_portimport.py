"""Importar datos de recompilación de un puerto de la familia XenonRecomp a formato rexglue."""
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from reforge import portimport as pi  # noqa: E402

fallos = []


def check(cond, msg):
    print(("  ✔ " if cond else "  ✘ ") + msg)
    if not cond:
        fallos.append(msg)


tmp = tempfile.mkdtemp()

# Config de tablas de saltos estilo XenonRecomp ([[switch]] con base/r/default/labels)
switch_src = os.path.join(tmp, "Juego_switch.toml")
open(switch_src, "w").write(
    "# Generated by XenonAnalyse\n"
    "[[switch]]\nbase = 0x820996F4\nr = 10\ndefault = 0x8209A240\n"
    "labels = [ 0x82099820, 0x82099850, 0x82099888 ]\n\n"
    "[[switch]]\nbase = 0x82100000\nr = 3\nlabels = [ 0x82100010, 0x82100020 ]\n")

# Config principal con la lista de funciones
main_src = os.path.join(tmp, "Juego.toml")
open(main_src, "w").write(
    '[main]\nfile_path = "x.xex"\n'
    "functions = [\n  { address = 0x8237F8F8, size = 0xA24 },\n  { address = 0x82380320, size = 0x6C },\n]\n")

print("Convierte [[switch]] de XenonRecomp a [[switch_tables]] de rexglue")
text, n = pi.convert_switch_tables(switch_src)
check(n == 2, "convierte las dos tablas")
check("[[switch_tables]]" in text and "address = 0x820996F4" in text and "register = 10" in text,
      "usa las claves de rexglue (address/register), no base/r")
check("0x82099820" in text and "default" not in text, "mantiene las etiquetas y descarta claves que rexglue no usa")
import tomllib  # noqa: E402
d = tomllib.loads(text)
check(len(d["switch_tables"]) == 2 and d["switch_tables"][0]["register"] == 10, "el resultado es TOML válido")

print("Lee la lista de funciones")
funcs = pi.read_functions(main_src)
check(funcs == [(0x8237F8F8, 0xA24), (0x82380320, 0x6C)], "lee direcciones y tamaños")

print("Aplica el perfil a un proyecto: escribe el include y lo engancha en el manifest")
root = tempfile.mkdtemp()
open(os.path.join(root, "reforge_functions.toml"), "w").write("[functions]\n0x82380320 = {}\n")   # una ya existe
open(os.path.join(root, "j_manifest.toml"), "w").write('[entrypoint]\nincludes = ["reforge_functions.toml"]\n')
res = pi.apply_profile(root, main_src, switch_src)
check(res["switch_tables"] == 2, "informa de las tablas aplicadas")
check(os.path.isfile(os.path.join(root, pi.SWITCH_FILE)), "escribe el archivo de tablas de saltos")
man = open(os.path.join(root, "j_manifest.toml")).read()
check(pi.SWITCH_FILE in man, "añade las tablas al manifest")
fn = open(os.path.join(root, "reforge_functions.toml")).read()
check("0x8237F8F8" in fn, "añade la función nueva")
check(fn.count("0x82380320") == 1, "no duplica una función que ya estaba")

print()
if fallos:
    print(f"FALLOS: {len(fallos)}")
    sys.exit(1)
print("OK")
